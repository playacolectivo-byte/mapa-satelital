import assert from 'node:assert/strict';
import {readFileSync,writeFileSync,renameSync,existsSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {applyPhotoVisualReview} from '../lib/photo-visual-review.ts';
import {applyPhotoDigitization} from '../lib/photo-digitization.ts';
import {applyPhotoPilotReview} from '../lib/photo-pilot-review.ts';
import {applyUserShorelineGuides} from '../lib/user-shoreline-guides.ts';
import {applyMunicipalShorelineReview} from '../lib/municipal-shoreline-review.ts';
import {validatePhotoCoast} from '../lib/photo-coast.ts';

const root=new URL('../',import.meta.url),folder='public/data/shorelines/photo-alignment/';
const read=p=>JSON.parse(readFileSync(new URL(p,root),'utf8'));
const digest=bytes=>createHash('sha256').update(bytes).digest('hex');
const raw=readFileSync(new URL(folder+'revised-data.json',root)),sha=digest(raw);
let upstream=applyPhotoVisualReview(validatePhotoCoast(JSON.parse(raw)),read(folder+'revised-visual-review.json'),sha);
upstream=applyPhotoDigitization(upstream,read(folder+'manual-digitization-20261103.json'),sha);
upstream=applyPhotoPilotReview(upstream,read(folder+'manual-progreso-oeste-20261105.json'),sha);
upstream=applyUserShorelineGuides(upstream,read(folder+'user-guides-2011-20261105.json'),sha);
const mainPath=folder+'manual-hunucma-20261105.json';
const snapshotPath='work/hunucma-additional-review-20261106/main-before-additional.json';
const main=existsSync(new URL(snapshotPath,root))?read(snapshotPath):read(mainPath);
const candidatePath='work/hunucma-additional-review-20261106/approved-additional.json';
const bytes=readFileSync(new URL(candidatePath,root)),additional=JSON.parse(bytes);
const originalMunicipal=read('public/data/municipalities/hunucma/photos.json');
const applied=applyMunicipalShorelineReview(upstream,main,sha);
const byId=new Map(upstream.targets.map(t=>[t.id,t]));
const afterMain=new Map(applied.targets.map(t=>[t.id,t]));
const localById=new Map(originalMunicipal.targets.map(t=>[t.id,t]));
const seen=new Set([...main.corrections,...main.reviewed_readings].map(c=>c.profile_id+':'+c.capture));
assert.equal(additional.data_sha256,sha);assert.equal(additional.model_sha256,upstream.model_sha256);
assert.equal(additional.states.length,394);
assert.equal(new Set(additional.states.map(r=>r.profile_id+':'+r.capture)).size,394);
const normalized=[];
const corrections=additional.corrections.map(c=>{
 assert.ok(!seen.has(c.profile_id+':'+c.capture));
 const previous=byId.get(c.profile_id).readings.find(r=>r.capture===c.capture);
 const current=afterMain.get(c.profile_id).readings.find(r=>r.capture===c.capture);
 const local=localById.get(c.profile_id).readings.find(r=>r.capture===c.capture);
 assert.equal(local.offset_m,current.offset_m);assert.equal(local.accepted,current.accepted);
 assert.equal(c.original_offset_m,current.offset_m);assert.equal(c.original_accepted,current.accepted);
 assert.equal(previous.offset_m,current.offset_m,'Earlier review unexpectedly moved an additional reading');
 if(previous.accepted!==c.original_accepted)normalized.push({profile_id:c.profile_id,capture:c.capture,municipal_original_accepted:c.original_accepted,upstream_original_accepted:previous.accepted,offset_m:previous.offset_m});
 return {...c,original_offset_m:previous.offset_m,original_accepted:previous.accepted};
});
if(process.argv.includes('--check')){
 console.log(JSON.stringify({additional_corrections:corrections.length,pending:additional.pending_readings.length,guard_normalizations:normalized}));
 process.exit(0);
}
const qaPath='docs/qa/hunucma-additional-independent-review-20261106.json',qa=read(qaPath);
assert.equal(qa.status,'independent_visual_review_complete');assert.equal(qa.readings_reviewed,394);
assert.equal(qa.approved_additional_sha256,digest(bytes));
assert.equal(additional.status,'independently_reviewed');
const sourceIds=new Set(main.sources.map(s=>s.id));
for(const s of additional.sources)assert.ok(!sourceIds.has(s.id),'Duplicate source view');
const merged={...main,last_review_date:'2026-11-06',sources:[...main.sources,...additional.sources],corrections:[...main.corrections,...corrections],rejected_readings:[...main.rejected_readings,...additional.rejected_readings],pending_readings:[...(main.pending_readings??[]),...additional.pending_readings],additional_review:{readings_reviewed:394,accepted:corrections.length,pending:additional.pending_readings.length,first_pass:candidatePath,first_pass_sha256:digest(bytes),second_pass:qaPath,second_pass_sha256:digest(readFileSync(new URL(qaPath,root))),source_photos_sha256:additional.source_photos_sha256,guard_normalizations:normalized}};
validatePhotoCoast(applyMunicipalShorelineReview(upstream,merged,sha));
if(!existsSync(new URL(snapshotPath,root)))writeFileSync(new URL(snapshotPath,root),JSON.stringify(main,null,2)+'\n');
writeFileSync(new URL(mainPath+'.tmp',root),JSON.stringify(merged,null,2)+'\n');
renameSync(new URL(mainPath+'.tmp',root),new URL(mainPath,root));
writeFileSync(new URL('docs/qa/hunucma-additional-integration-20261106.json',root),JSON.stringify({status:'pass',source:candidatePath,sha256:digest(bytes),second_pass:qaPath,corrections:corrections.length,pending:additional.pending_readings.length,guard_normalizations:normalized},null,2)+'\n');
console.log(JSON.stringify({merged_corrections:merged.corrections.length,confirmed:merged.reviewed_readings.length,pending:merged.pending_readings.length,guard_normalizations:normalized.length}));
